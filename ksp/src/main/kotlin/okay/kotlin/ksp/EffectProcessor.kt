class EffectProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        EffectProcessor(environment.codeGenerator, environment.logger)
}

/**
 * FOR EACH INTERFACE MARKED `@Effect`, its wrapper: `fun Name.intercepted(interceptor: Interceptor): Name`, whose
 * every suspend function goes through the interceptor as an `Operation` — the effect's name, the function's, its
 * arguments — and then to the capability it wraps. A function that is not suspend, and a property, is passed on as it
 * is: an interceptor is a suspend function.
 */
class EffectProcessor(private val generator: CodeGenerator, private val logger: KSPLogger) : SymbolProcessor {
    override fun process(resolver: Resolver): List<KSAnnotated> {
        val marked = resolver.getSymbolsWithAnnotation("okay.kotlin.Effect").toList()
        val later = marked.filterNot { it.validate(enableNewFeatures = true) }
        for (symbol in marked - later.toSet()) {
            if (symbol is KSClassDeclaration && symbol.classKind == ClassKind.INTERFACE) generate(symbol)
            else logger.error("@Effect marks an interface: an effect's operations", symbol)
        }
        return later
    }

    private fun generate(effect: KSClassDeclaration) {
        val pkg = effect.packageName.asString()
        val name = generateSequence(effect) { it.parentDeclaration as? KSClassDeclaration }.toList().reversed()
            .joinToString(".") { it.simpleName.asString() }
        val typeParams = effect.typeParameters
        val self = name +
            if (typeParams.isEmpty()) "" else typeParams.joinToString(", ", "<", ">") { it.name.asString() }
        if (typeParams.isNotEmpty() && effect.getAllSuperTypes().any { it.declaration.typeParameters.isNotEmpty() }) {
            logger.error("@Effect of a generic interface that extends a generic one: write its wrapper by hand", effect)
            return
        }
        val members = StringBuilder()
        for (f in effect.getAllFunctions()) {
            if (f.isPrivate() || f.parentDeclaration?.qualifiedName?.asString() == "kotlin.Any") continue
            members.append(function(effect, f, name.substringAfterLast('.')) ?: return)
        }
        for (p in effect.getAllProperties()) if (!p.isPrivate()) members.append(property(effect, p))
        val visibility = if (Modifier.INTERNAL in effect.modifiers) "internal " else ""
        val code = buildString {
            appendLine("// Generated by okay-kotlin from $name: each suspend function through the interceptor.")
            appendLine("// Do not edit.")
            if (pkg.isNotEmpty()) appendLine("package $pkg").appendLine()
            val (declared, where) = typeParameters(typeParams)
            appendLine("${visibility}fun $declared$self.intercepted(")
            appendLine("    okayInterceptor: okay.kotlin.Interceptor,")
            appendLine("): $self$where {")
            appendLine("    val okayInner = this")
            appendLine("    return object : $self {")
            append(members)
            appendLine("    }")
            appendLine("}")
        }
        val file = name.replace('.', '_') + "Intercepted"
        generator.createNewFile(Dependencies(false, effect.containingFile ?: return), pkg, file)
            .bufferedWriter().use { it.write(code) }
    }

    private fun function(effect: KSClassDeclaration, f: KSFunctionDeclaration, effectName: String): String? {
        if (f.extensionReceiver != null) {
            logger.error("@Effect with an extension function: write its wrapper by hand", f)
            return null
        }
        val inherited = f.parentDeclaration != effect
        val asMember = if (inherited) f.asMemberOf(effect.asStarProjectedType()) else null
        val params = f.parameters.mapIndexed { i, p ->
            val type = asMember?.parameterTypes?.get(i)?.let(::render) ?: render(p.type.resolve())
            Triple(p.name?.asString() ?: "p$i", type, p.isVararg)
        }
        val returns = (asMember?.returnType ?: f.returnType?.resolve())?.let(::render) ?: "kotlin.Unit"
        val fname = f.simpleName.asString()
        val suspend = Modifier.SUSPEND in f.modifiers
        val declared = params.joinToString(", ") { (n, t, vararg) -> (if (vararg) "vararg " else "") + "$n: $t" }
        val passed = params.joinToString(", ") { (n, _, vararg) -> if (vararg) "*$n" else n }
        val args = params.joinToString(", ", "listOf(", ")") { (n, _, vararg) -> if (vararg) "$n.toList()" else n }
        val call = "okayInner.$fname($passed)"
        val op = "okay.kotlin.Operation(\"$effectName\", \"$fname\", $args)"
        val body = if (suspend) "okayInterceptor.around($op) {\n" +
            "                $call\n            }" else call
        val (typeParams, where) = typeParameters(f.typeParameters)
        return "        override ${if (suspend) "suspend " else ""}fun $typeParams" +
            "$fname($declared): $returns$where =\n            $body\n"
    }

    private fun property(effect: KSClassDeclaration, p: KSPropertyDeclaration): String {
        val type = if (p.parentDeclaration != effect) render(p.asMemberOf(effect.asStarProjectedType()))
        else render(p.type.resolve())
        val n = p.simpleName.asString()
        return if (p.isMutable) "        override var $n: $type\n            get() = okayInner.$n\n" +
            "            set(value) {\n                okayInner.$n = value\n            }\n"
        else "        override val $n: $type get() = okayInner.$n\n"
    }

    /** type parameters as declared, `<T : A, U>`, and the `where` clause of those with more than one bound */
    private fun typeParameters(params: List<KSTypeParameter>): Pair<String, String> {
        if (params.isEmpty()) return "" to ""
        val bounded = params.map { tp ->
            tp to tp.bounds.map { render(it.resolve()) }.filter { it != "kotlin.Any?" }.toList()
        }
        val declared = bounded.joinToString(", ", "<", "> ") { (tp, bounds) ->
            val bound = if (bounds.size == 1) " : ${bounds[0]}" else ""
            (if (tp.isReified) "reified " else "") + tp.name.asString() + bound
        }
        val where = bounded.filter { it.second.size > 1 }
            .flatMap { (tp, bounds) -> bounds.map { "${tp.name.asString()} : $it" } }
        return declared to if (where.isEmpty()) "" else " where ${where.joinToString(", ")}"
    }

    /** a type as source: qualified names, its arguments, function types as Kotlin writes them */
    private fun render(t: KSType): String {
        val nullable = if (t.isMarkedNullable) "?" else ""
        if (t.isFunctionType || t.isSuspendFunctionType) {
            val params = t.arguments.dropLast(1).joinToString(", ") { argument(it) }
            val fn = (if (t.isSuspendFunctionType) "suspend " else "") + "($params) -> " + argument(t.arguments.last())
            return if (t.isMarkedNullable) "($fn)?" else fn
        }
        val decl = t.declaration
        val name = if (decl is KSTypeParameter) decl.name.asString()
        else decl.qualifiedName?.asString() ?: decl.simpleName.asString()
        val args = if (t.arguments.isEmpty()) "" else t.arguments.joinToString(", ", "<", ">") { argument(it) }
        return name + args + nullable
    }

    private fun argument(a: KSTypeArgument): String {
        val type = a.type?.resolve() ?: return "*"
        return when (a.variance) {
            Variance.STAR -> "*"
            Variance.CONTRAVARIANT -> "in ${render(type)}"
            Variance.COVARIANT -> "out ${render(type)}"
            Variance.INVARIANT -> render(type)
        }
    }
}
